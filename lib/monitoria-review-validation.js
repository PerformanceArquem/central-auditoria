// Pure validation for the Mini Central. Never trust a browser-supplied AI score.
export const RUBRIC={
 chat:[5,5,5,12.5,12.5,10,5,10,5,5,10,5,10],
 voice:[null,7.5,7.5,12.5,12.5,10,5,10,5,5,10,5,10]
};
export const PARTIAL={
 chat:[null,null,2.5,7.5,7.5,5,null,7,3,null,null,null,7],
 voice:[null,null,4,7.5,7.5,5,null,7,null,null,null,null,7]
};
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const clean=(x,n)=>typeof x==='string'?x.trim().slice(0,n):'';
const isDecision=s=>['conforme','parcial','nao_conforme','nao_verificavel','nao_aplicavel'].includes(s);
export function prepareReview(body,userId){
 if(!body||!['chat','voice'].includes(body.channel))throw Error('Canal inválido');
 const {channel}=body;
 const requestId=clean(body.requestId,40);
 if(!UUID.test(requestId))throw Error('Identificador da avaliação inválido');
 const sourceId=clean(body.sourceId,80);
 if(!/^[A-Za-z0-9_-]{1,80}$/.test(sourceId))throw Error('Identificador do atendimento inválido');
 const sector=clean(body.sector,100),collaborator=clean(body.collaborator,160);
 const reviewer=clean(body.reviewer,160);
 const monitoredAt=clean(body.monitoredAt,10);
 if(!reviewer)throw Error('Informe o responsável pela monitoria');
 if(!/^\d{4}-\d{2}-\d{2}$/.test(monitoredAt)||!Number.isFinite(Date.parse(monitoredAt+'T12:00:00Z'))||
   new Date(monitoredAt+'T12:00:00Z').toISOString().slice(0,10)!==monitoredAt)throw Error('Data da monitoria inválida');
 const recordingKind=body.channel==='voice'?clean(body.recordingKind,15):'';
 if(recordingKind&&!['inbound','outbound'].includes(recordingKind))throw Error('Origem da gravação inválida');
 if(!sector||!collaborator)throw Error('Informe setor e colaborador');
 const analysis=body.analysis;
 if(!analysis||analysis.version!=='monitoria-suporte-2026-11-17'||analysis.channel!==channel||
  !Array.isArray(analysis.criteria)||!Array.isArray(analysis.critical))
  throw Error('Análise incompatível com as regras vigentes');
 const values=RUBRIC[channel],partial=PARTIAL[channel],items=[];
 const byId=new Map(analysis.criteria.map(x=>[x?.id,x]));
 if(byId.size!==analysis.criteria.length||byId.size>13)throw Error('Critérios duplicados ou incompletos');
 let deducted=0;
 for(let i=0;i<values.length;i++){
  const max=values[i];if(max===null)continue;
  const id='R'+String(i+1).padStart(2,'0'),r=byId.get(id);
  if(!r||!isDecision(r.decision))throw Error('Critério obrigatório ausente: '+id);
  let d=0;
  if(r.decision==='nao_conforme')d=max;
  if(r.decision==='parcial'){
   if(partial[i]===null)throw Error('Critério sem desconto parcial: '+id);
   d=partial[i];
  }
  const evidence=clean(r.evidence,600);
  // Noncompliance cannot be asserted without verbatim evidence. Full source is
  // deliberately NOT persisted; a Quality analyst must review the excerpt.
  if(d>0&&!evidence)throw Error('Critério sem evidência: '+id);
  deducted+=d;
  items.push({id,decision:r.decision,deducted:d,evidence,reason:clean(r.reason,450)});
 }
 const critical=[];
 if(analysis.critical.length>4)throw Error('Falhas críticas excedem limite');
 const codes=new Set();
 for(const c of analysis.critical){
  if(!['Z1','Z2','Z3','Z4'].includes(c?.code)||codes.has(c.code))throw Error('Código crítico inválido');
  codes.add(c.code);
  const evidence=clean(c.evidence,600),suspected=c.suspected===true&&!!evidence;
  critical.push({code:c.code,suspected,evidence:suspected?evidence:''});
 }
 const flagged=critical.some(c=>c.suspected);
 const score=flagged?0:Math.max(0,100-deducted);
 // Fail closed: do not allow tampering with score generated by deterministic rubric.
 if(Math.abs(Number(analysis.scoreSuggestion)-score)>0.001)throw Error('Pontuação divergente da planilha');
 return {
  client_request_id:requestId,created_by:userId,channel,source_id:sourceId,
  sector,collaborator_name:collaborator,reviewer_name:reviewer,monitored_at:monitoredAt,
  recording_kind:recordingKind||null,evidence_reference:sourceId,ruleset_version:analysis.version,
  score_suggested:score,critical_suspected:flagged,critical_findings:critical,
  criteria:items
 };
}
export function isUuid(x){return UUID.test(String(x||''));}
